#include <behaviortree_cpp/loggers/bt_cout_logger.h>

#include <behaviortree_ros2/tree_execution_server.hpp>
#include <fstream>

#include "behaviortree_cpp/xml_parsing.h"

namespace
{
static const auto kLogger = rclcpp::get_logger("bt_action_server");

bool writeXMLToDisk(const BT::StringView& path, const std::function<std::string()>& generator_function)
{
  // Generate XSD string
  std::string xml;
  try
  {
    xml = generator_function();
  }
  catch (const std::exception& ex)
  {
    RCLCPP_ERROR_STREAM(kLogger, "XML generation failed: " << ex.what());
    return false;
  }

  // Add a disclaimer comment
  size_t pos = xml.find('\n');
  if (pos != std::string::npos)
  {
    xml.insert(pos + 1, "<!--  This document was autogenerated, do not edit. -->\n");
  }

  // Write XML to disk
  const std::filesystem::path out(path);
  std::ofstream ofs(out);
  if (!ofs)
  {
    RCLCPP_ERROR_STREAM(kLogger, "Cannot open output file: " << path);
    return false;
  }
  ofs << xml;

  RCLCPP_INFO_STREAM(kLogger, "XML written to: " << path);
  return true;
}

}  // namespace

class NDTActionServer : public BT::TreeExecutionServer
{
public:
  NDTActionServer(const rclcpp::NodeOptions& options)
    : TreeExecutionServer(options)
  {
    this->node()->declare_parameter("tree_schema_path", rclcpp::ParameterValue(""));
    this->node()->declare_parameter("tree_nodes_model_path", rclcpp::ParameterValue(""));
    this->node()->declare_parameter("exit_after_writing_schema", rclcpp::ParameterValue(false));
  }

  void onTreeCreated(BT::Tree& tree) override
  {
    logger_cout_ = std::make_shared<BT::StdCoutLogger>(tree);
    globalBlackboard()->set("payload", goalPayload());
  }

  void registerNodesIntoFactory(BT::BehaviorTreeFactory& factory) override
  {
    // Optionally load custom plugins here

    const std::string tree_schema_path = this->node()->get_parameter("tree_schema_path").as_string();
    const std::string tree_nodes_model_path = this->node()->get_parameter("tree_nodes_model_path").as_string();
    const bool exit_after_writing_schema = this->node()->get_parameter("exit_after_writing_schema").as_bool();
    if (tree_schema_path.empty() && tree_nodes_model_path.empty())
    {
      if (!exit_after_writing_schema)
      {
        // No path provided, don't export schema
        return;
      }
      RCLCPP_FATAL_STREAM(kLogger,
                          "'tree_schema_path' and 'tree_nodes_model_path' parameters empty, nothing to export.");
      std::exit(1);
    }
    bool success = true;
    if (!tree_schema_path.empty())
    {
      // Write XSD schema to disk
      success &= writeXMLToDisk(tree_schema_path, [&factory]() { return BT::writeTreeXSD(factory); });
    }
    if (!tree_nodes_model_path.empty())
    {
      // Write tree nodes model xml to disk (used for Groot2)
      success &=
          writeXMLToDisk(tree_nodes_model_path, [&factory]() { return BT::writeTreeNodesModelXML(factory, false); });
    }
    if (exit_after_writing_schema)
    {
      // Done writing the schema, so we can exit
      std::exit(success ? 0 : 1);
    }
  }

private:
  std::shared_ptr<BT::StdCoutLogger> logger_cout_;
};

int main(int argc, char* argv[])
{
  rclcpp::init(argc, argv);
  rclcpp::NodeOptions options;
  auto action_server = std::make_shared<NDTActionServer>(options);
  rclcpp::spin(action_server->node());
  rclcpp::shutdown();
  return 0;
}
